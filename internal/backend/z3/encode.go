// Package z3 implements bounded model checking via the Z3 SMT solver.
package z3

import (
	"fmt"
	"strings"

	"github.com/BoundlessProducts/spectre/pkg/ast"
)

// Encode produces a complete SMT-LIB2 script for bounded model checking
// to the given depth. It encodes the question: "Is there an execution of
// length ≤ depth that violates any invariant?"
func Encode(file *ast.File, params map[string]string, depth int) (string, error) {
	var vars []*ast.VariableDecl
	var paramDecls []*ast.ParamDecl
	var initDecl *ast.InitDecl
	var actions []*ast.ActionDecl
	var invariants []*ast.InvariantDecl
	var enums []*ast.EnumDecl

	for _, d := range file.Decls {
		switch v := d.(type) {
		case *ast.VariableDecl:
			vars = append(vars, v)
		case *ast.ParamDecl:
			paramDecls = append(paramDecls, v)
		case *ast.InitDecl:
			initDecl = v
		case *ast.ActionDecl:
			actions = append(actions, v)
		case *ast.InvariantDecl:
			invariants = append(invariants, v)
		case *ast.EnumDecl:
			enums = append(enums, v)
		}
	}

	// Build param value map: name → string value (from overrides only; no Default on ParamDecl).
	paramVals := make(map[string]string)
	for _, p := range paramDecls {
		paramVals[p.Name] = "0" // safe fallback if not overridden
	}
	for k, v := range params {
		paramVals[k] = v
	}

	var sb strings.Builder

	sb.WriteString("; SMT-LIB2 BMC encoding generated by Spectre\n")
	sb.WriteString("(set-logic ALL)\n\n")

	// Declare enum datatypes.
	for _, e := range enums {
		sb.WriteString(fmt.Sprintf("(declare-datatypes () ((%s", e.Name))
		for _, v := range e.Values {
			sb.WriteString(fmt.Sprintf(" (%s)", v))
		}
		sb.WriteString(")))\n")
	}
	if len(enums) > 0 {
		sb.WriteString("\n")
	}

	// Declare variable constants for steps 0..depth.
	for step := 0; step <= depth; step++ {
		sb.WriteString(fmt.Sprintf("; Step %d variables\n", step))
		for _, v := range vars {
			sort := smtSort(v.Type, enums)
			sb.WriteString(fmt.Sprintf("(declare-const %s_%d %s)\n", v.Name, step, sort))
		}
	}
	sb.WriteString("\n")

	// Assert init at step 0.
	sb.WriteString("; Init\n")
	assigned := map[string]bool{}
	if initDecl != nil && initDecl.Body != nil {
		for _, stmt := range initDecl.Body.Statements {
			if a, ok := stmt.(*ast.AssignStmt); ok {
				if id, ok := a.Left.(*ast.Ident); ok {
					val := exprToSMT(a.Right, 0, paramVals)
					sb.WriteString(fmt.Sprintf("(assert (= %s_0 %s))\n", id.Name, val))
					assigned[id.Name] = true
				}
			}
		}
	}
	for _, v := range vars {
		if !assigned[v.Name] {
			sb.WriteString(fmt.Sprintf("(assert (= %s_0 %s))\n", v.Name, defaultSMTVal(v.Type, enums)))
		}
	}
	sb.WriteString("\n")

	// Assert transition relation at each step 0..depth-1.
	for step := 0; step < depth; step++ {
		sb.WriteString(fmt.Sprintf("; Transition at step %d\n", step))
		if len(actions) == 0 {
			// No actions: stutter (all vars unchanged).
			parts := make([]string, len(vars))
			for i, v := range vars {
				parts[i] = fmt.Sprintf("(= %s_%d %s_%d)", v.Name, step+1, v.Name, step)
			}
			sb.WriteString(fmt.Sprintf("(assert (and %s))\n\n", strings.Join(parts, " ")))
			continue
		}

		sb.WriteString("(assert (or\n")
		for _, action := range actions {
			sb.WriteString(fmt.Sprintf("  ; action %s\n", action.Name))
			var parts []string
			assignedByAction := map[string]bool{}

			if action.Body != nil {
				for _, stmt := range action.Body.Statements {
					switch s := stmt.(type) {
					case *ast.RequireStmt:
						parts = append(parts, exprToSMT(s.Condition, step, paramVals))
					case *ast.AssignStmt:
						if id, ok := s.Left.(*ast.Ident); ok {
							assignedByAction[id.Name] = true
							rhs := exprToSMT(s.Right, step, paramVals)
							parts = append(parts, fmt.Sprintf("(= %s_%d %s)", id.Name, step+1, rhs))
						}
					}
				}
			}
			// Unchanged vars.
			for _, v := range vars {
				if !assignedByAction[v.Name] {
					parts = append(parts, fmt.Sprintf("(= %s_%d %s_%d)", v.Name, step+1, v.Name, step))
				}
			}

			switch len(parts) {
			case 0:
				sb.WriteString("  true\n")
			case 1:
				sb.WriteString(fmt.Sprintf("  %s\n", parts[0]))
			default:
				sb.WriteString(fmt.Sprintf("  (and %s)\n", strings.Join(parts, " ")))
			}
		}
		// Stutter clause: when no action is enabled the system stays in place.
		// Without this, a deadlocked state produces (assert (or false ... false))
		// which is UNSAT — the solver would vacuously report "safe".
		stutterParts := make([]string, len(vars))
		for i, v := range vars {
			stutterParts[i] = fmt.Sprintf("(= %s_%d %s_%d)", v.Name, step+1, v.Name, step)
		}
		if len(stutterParts) == 1 {
			sb.WriteString(fmt.Sprintf("  ; stutter (no action fires)\n  %s\n", stutterParts[0]))
		} else if len(stutterParts) > 1 {
			sb.WriteString(fmt.Sprintf("  ; stutter (no action fires)\n  (and %s)\n", strings.Join(stutterParts, " ")))
		}
		sb.WriteString("))\n\n")
	}

	// Assert that some invariant is violated at some step.
	if len(invariants) > 0 {
		sb.WriteString("; Invariant violation check\n")
		var stepViolations []string
		for step := 0; step <= depth; step++ {
			var invParts []string
			for _, inv := range invariants {
				invParts = append(invParts, exprToSMT(inv.Condition, step, paramVals))
			}
			var allInvs string
			if len(invParts) == 1 {
				allInvs = invParts[0]
			} else {
				allInvs = fmt.Sprintf("(and %s)", strings.Join(invParts, " "))
			}
			stepViolations = append(stepViolations, fmt.Sprintf("(not %s)", allInvs))
		}
		if len(stepViolations) == 1 {
			sb.WriteString(fmt.Sprintf("(assert %s)\n", stepViolations[0]))
		} else {
			sb.WriteString(fmt.Sprintf("(assert (or\n  %s\n))\n", strings.Join(stepViolations, "\n  ")))
		}
		sb.WriteString("\n")
	}

	sb.WriteString("(check-sat)\n")
	sb.WriteString("(get-model)\n")

	return sb.String(), nil
}

// exprToSMT converts a Spectre expression to an SMT-LIB2 term at a given step.
// Unprimed identifiers get suffix _step; primed get suffix _(step+1).
// Param names are substituted with their literal values.
func exprToSMT(expr ast.Expr, step int, params map[string]string) string {
	if expr == nil {
		return "true"
	}
	switch e := expr.(type) {
	case *ast.Ident:
		if !e.Prime {
			if v, ok := params[e.Name]; ok {
				return v
			}
			return fmt.Sprintf("%s_%d", e.Name, step)
		}
		return fmt.Sprintf("%s_%d", e.Name, step+1)

	case *ast.BasicLit:
		switch e.Kind {
		case ast.BoolLit:
			return e.Value // SMT-LIB2 uses lowercase true/false
		default:
			return e.Value
		}

	case *ast.BinaryExpr:
		l := exprToSMT(e.Left, step, params)
		r := exprToSMT(e.Right, step, params)
		switch e.Op {
		case ast.Add:
			return fmt.Sprintf("(+ %s %s)", l, r)
		case ast.Sub:
			return fmt.Sprintf("(- %s %s)", l, r)
		case ast.Mul:
			return fmt.Sprintf("(* %s %s)", l, r)
		case ast.Div:
			return fmt.Sprintf("(div %s %s)", l, r)
		case ast.Eq:
			return fmt.Sprintf("(= %s %s)", l, r)
		case ast.Neq:
			return fmt.Sprintf("(not (= %s %s))", l, r)
		case ast.Lt:
			return fmt.Sprintf("(< %s %s)", l, r)
		case ast.Gt:
			return fmt.Sprintf("(> %s %s)", l, r)
		case ast.Leq:
			return fmt.Sprintf("(<= %s %s)", l, r)
		case ast.Geq:
			return fmt.Sprintf("(>= %s %s)", l, r)
		case ast.And:
			return fmt.Sprintf("(and %s %s)", l, r)
		case ast.Or:
			return fmt.Sprintf("(or %s %s)", l, r)
		case ast.In:
			return fmt.Sprintf("(member %s %s)", l, r)
		}

	case *ast.UnaryExpr:
		inner := exprToSMT(e.Expr, step, params)
		switch e.Op {
		case ast.Not:
			return fmt.Sprintf("(not %s)", inner)
		case ast.Neg:
			return fmt.Sprintf("(- %s)", inner)
		}

	case *ast.ParenExpr:
		return exprToSMT(e.X, step, params)

	case *ast.SetLiteral:
		if len(e.Elements) == 0 {
			return "(as emptyset (Set Int))"
		}
		result := fmt.Sprintf("(singleton %s)", exprToSMT(e.Elements[0], step, params))
		for _, el := range e.Elements[1:] {
			result = fmt.Sprintf("(union %s (singleton %s))", result, exprToSMT(el, step, params))
		}
		return result

	case *ast.ListLiteral:
		if len(e.Elements) == 0 {
			return "(as seq.empty (Seq Int))"
		}
		result := fmt.Sprintf("(seq.unit %s)", exprToSMT(e.Elements[0], step, params))
		for _, el := range e.Elements[1:] {
			result = fmt.Sprintf("(seq.++ %s (seq.unit %s))", result, exprToSMT(el, step, params))
		}
		return result

	case *ast.CallExpr:
		if sel, ok := e.Fun.(*ast.SelectorExpr); ok {
			obj := exprToSMT(sel.X, step, params)
			args := make([]string, len(e.Args))
			for i, a := range e.Args {
				args[i] = exprToSMT(a, step, params)
			}
			switch sel.Sel {
			case "union":
				if len(args) == 1 {
					return fmt.Sprintf("(union %s %s)", obj, args[0])
				}
			case "intersection":
				if len(args) == 1 {
					return fmt.Sprintf("(intersection %s %s)", obj, args[0])
				}
			case "difference":
				if len(args) == 1 {
					return fmt.Sprintf("(setdiff %s %s)", obj, args[0])
				}
			case "contains":
				if len(args) == 1 {
					return fmt.Sprintf("(member %s %s)", args[0], obj)
				}
			case "size":
				return fmt.Sprintf("(card %s)", obj)
			case "put":
				if len(args) == 2 {
					return fmt.Sprintf("(store %s %s %s)", obj, args[0], args[1])
				}
			case "get":
				if len(args) == 1 {
					return fmt.Sprintf("(select %s %s)", obj, args[0])
				}
			case "append":
				if len(args) == 1 {
					return fmt.Sprintf("(seq.++ %s (seq.unit %s))", obj, args[0])
				}
			case "head":
				return fmt.Sprintf("(seq.nth %s 0)", obj)
			case "tail":
				return fmt.Sprintf("(seq.extract %s 1 (- (seq.len %s) 1))", obj, obj)
			}
		}
		// Generic call — best effort
		fun := exprToSMT(e.Fun, step, params)
		args := make([]string, len(e.Args))
		for i, a := range e.Args {
			args[i] = exprToSMT(a, step, params)
		}
		if len(args) == 0 {
			return fun
		}
		return fmt.Sprintf("(%s %s)", fun, strings.Join(args, " "))
	}
	return "true"
}

// smtSort maps a Spectre type to its SMT-LIB2 sort.
func smtSort(t ast.Type, enums []*ast.EnumDecl) string {
	switch ty := t.(type) {
	case *ast.PrimitiveType:
		switch ty.Name {
		case "int":
			return "Int"
		case "bool":
			return "Bool"
		case "float":
			return "Real"
		case "str":
			return "Int" // approximation
		}
	case *ast.EnumType:
		return ty.Name
	case *ast.NamedType:
		for _, e := range enums {
			if e.Name == ty.Name {
				return ty.Name
			}
		}
		return "Int"
	case *ast.SetType:
		return fmt.Sprintf("(Set %s)", smtSort(ty.Element, enums))
	case *ast.MapType:
		return fmt.Sprintf("(Array %s %s)", smtSort(ty.Key, enums), smtSort(ty.Value, enums))
	case *ast.ListType:
		return fmt.Sprintf("(Seq %s)", smtSort(ty.Element, enums))
	}
	return "Int"
}

// defaultSMTVal returns a default SMT value for a type.
func defaultSMTVal(t ast.Type, enums []*ast.EnumDecl) string {
	switch ty := t.(type) {
	case *ast.PrimitiveType:
		switch ty.Name {
		case "bool":
			return "false"
		case "float":
			return "0.0"
		default:
			return "0"
		}
	case *ast.EnumType:
		for _, e := range enums {
			if e.Name == ty.Name && len(e.Values) > 0 {
				return e.Values[0]
			}
		}
	case *ast.NamedType:
		for _, e := range enums {
			if e.Name == ty.Name && len(e.Values) > 0 {
				return e.Values[0]
			}
		}
	case *ast.SetType:
		return fmt.Sprintf("(as emptyset (Set %s))", smtSort(ty.Element, enums))
	case *ast.MapType:
		return fmt.Sprintf("((as const (Array %s %s)) %s)", smtSort(ty.Key, enums), smtSort(ty.Value, enums), defaultSMTVal(ty.Value, enums))
	case *ast.ListType:
		return fmt.Sprintf("(as seq.empty (Seq %s))", smtSort(ty.Element, enums))
	}
	return "0"
}
